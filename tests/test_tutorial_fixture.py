"""Spec 42 §4 acceptance tests 1-3 against the REAL committed tutorial fixture
(`tests/data/tutorial/`, run-book 43). Skipped whole-module until the fixture
exists -- it is built on an Azure VM (run-book 43 Steps 1-5) and landed home,
not generated by this repo's test suite (spec 42 D4).

**Acceptance test 2 (spec 42 §8 amendment A2).** A1's revised test 2 asked this
module to assert the fixture's offset **equals the source catalog's row** --
"copied from the source, not invented". That is not achievable here and A2
records why: run-book 43 Step 6 runs this suite with the network disconnected,
so the source (blob) catalog is unreachable by design, and nothing shipped in
the fixture can distinguish a copied offset from an invented one. A2 therefore
**moves the source-equality gate to where the source is reachable** -- the
generator's own `_result.json` (`offset_sources` / `all_offsets_declared`,
run-book 43 Steps 2 and 4) -- and leaves this module the two checks that ARE
sound offline:

- the declaration round-trips through the declaration API (ADR 0013), and where
  a granule id carries a baseline token it agrees with that token's
  independently-derived value (D1's technique, live only on the local-CDSE
  fallback path -- MPC ids carry no token);
- the offset is one of the two physically meaningful S2 L2A values, and the
  decisive check that a wrong offset would fail is acceptance test 3's
  post-offset reflectance range.

An unconditional `== -1000` was deliberately NOT used: a generator that
hardcoded -1000 would pass it, which is exactly the failure mode A1 set out to
exclude, so it reads as a stronger check than it is.
"""

